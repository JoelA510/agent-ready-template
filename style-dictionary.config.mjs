// Style Dictionary pipeline: tokens/**/*.json (W3C DTCG format) -> src/styles/tokens/*.css (web)
// and platforms/{js,ios,android}/* (JS/TS + JSON, Swift, Android XML) for non-web consumers.
//
// All token $values are authored as final, ready-to-use CSS strings (e.g. "0.25rem",
// "#2f7f5f", "cubic-bezier(0.4, 0, 0.2, 1)"), so the CSS platforms only need name
// generation + $-reference resolution — no unit/color value transforms are registered
// there, same as before. The JS/iOS/Android platforms added below DO register a
// handful of custom value transforms (rem -> px/pt/dp/sp numbers, ms -> seconds/ms,
// hex -> native color literals) because those platforms need real typed values, not
// CSS strings. Those transforms are registered per StyleDictionary INSTANCE (via
// `instance.registerTransform`, never the static `StyleDictionary.registerTransform`),
// and are only ever referenced by name from the js/ios/android platform blocks — the
// css/light/dark platforms' `transforms` arrays never name them — so they cannot leak
// into and change the existing CSS output.
