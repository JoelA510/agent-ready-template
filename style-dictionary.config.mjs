// ---------------------------------------------------------------------------
// Shared value-parsing helpers
//
// Every non-color token in tokens/**/*.json is authored as a ready-to-use CSS string
// (a number plus an optional unit: "0.25rem", "150ms", "640px", "-0.02em", or a bare
// "100"/"1.1"). These helpers turn that string into a plain number so the JS/iOS/Android
// platforms can do real math with it instead of just re-printing the CSS string.
// ---------------------------------------------------------------------------

const REM_BASE_PX = 16; // 1rem = 16px: the browser default, and the base this repo's
// Tailwind config assumes — reused here as the same rem -> px/pt/dp/sp conversion
// factor across JS, iOS, and Android so all three platforms agree on one number.

/** Splits "0.25rem" -> { number: 0.25, unit: 'rem' }; "100" -> { number: 100, unit: '' }. */
function parseUnitValue(raw) {
  const match = `${raw}`.trim().match(/^(-?\d*\.?\d+)([a-zA-Z%]*)$/);
  if (!match) throw new Error(`Cannot parse numeric token value: "${raw}"`);
  return { number: parseFloat(match[1]), unit: match[2] };
}

/**
 * Converts an authored dimension string to a plain number:
 * - "rem" is scaled by REM_BASE_PX (spacing, radius, font sizes).
 * - "px" passes through unscaled (breakpoints are already in px).
 * - "em" passes through unscaled too (letterSpacing) — em is relative to the element's
 *   own font-size, not a fixed base, so there is no universally-correct px equivalent;
 *   the raw em coefficient is the most honest value to hand back.
 * - unitless numbers pass through as-is.
 */
function dimensionToNumber(raw) {
  const { number, unit } = parseUnitValue(raw);
  return unit === 'rem' ? number * REM_BASE_PX : number;
}

/** Converts an authored "150ms" duration string to the plain number 150. */
function durationToMs(raw) {
  return parseUnitValue(raw).number;
}

/** Rounds away floating point noise (e.g. 0.1 + 0.2) without rounding off real precision. */
function roundNum(n) {
  return Math.round(n * 1e6) / 1e6;
}

/** DTCG-aware `$type`/`type` accessor, mirroring the pattern style-dictionary's own
 * built-in transforms use internally. */
function getType(token, options) {
  return options.usesDtcg ? token.$type : token.type;
}

/** DTCG-aware `$value`/`value` accessor. */
function getValue(token, options) {
  return options.usesDtcg ? token.$value : token.value;
}

// Path-based predicates. This repo tags every spacing/radius/font-size/letterSpacing/
// breakpoint token with the single DTCG `$type: "dimension"` (there's no separate
// "fontSize" or "breakpoint" $type), so telling them apart for native output requires
// looking at the token's path rather than its $type.
const isBreakpointToken = (token) => token.path[0] === 'breakpoint';
const isFontSizeToken = (token) => token.path[0] === 'font' && token.path[1] === 'size';
const isLetterSpacingToken = (token) => token.path[0] === 'font' && token.path[1] === 'letterSpacing';

// A dimension token that native platforms can render as a fixed device unit (pt/dp/sp):
// spacing, radius, and font sizes — but not breakpoints (a media-query concept, not a
// device length) or letterSpacing (relative em, see dimensionToNumber above).
function isDeviceDimensionToken(token, options) {
  return getType(token, options) === 'dimension' && !isBreakpointToken(token) && !isLetterSpacingToken(token);
}

