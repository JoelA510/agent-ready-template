/** Pretty-prints a plain JS value (string/number/nested object) as a TS/JS object
 * literal. Keys are always JSON-quoted (simplest way to safely handle numeric-looking
 * keys like "500" or hyphenated ones like "card-foreground"). */
function toObjectLiteral(value, indent = '') {
  if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
    const nextIndent = `${indent}  `;
    const entries = Object.entries(value)
      .map(([key, val]) => `${nextIndent}${JSON.stringify(key)}: ${toObjectLiteral(val, nextIndent)},`)
      .join('\n');
    return `{\n${entries}\n${indent}}`;
  }
  if (typeof value === 'number') return String(value);
  return JSON.stringify(value);
}

