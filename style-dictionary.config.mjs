// ---------------------------------------------------------------------------
// Custom transforms for the JS/iOS/Android platforms.
//
// Registered per StyleDictionary INSTANCE (instance.registerTransform, not the static
// StyleDictionary.registerTransform) and only ever named from the js/ios/android
// platform blocks below, so they never touch the css/light/dark platforms' output.
// `transitive: true` is required on the value transforms that convert units: the light/dark
// semantic tokens are `{...}`-alias references, and without `transitive: true`
// style-dictionary skips re-running a value transform on a token whose *original* authored
// value was a reference (see style-dictionary/lib/transform/token.js). The one exception is
// `color/css-to-hex`, which must NOT be transitive; its own comment says why.
// ---------------------------------------------------------------------------

function registerPlatformTransforms(instance) {
  // Style Dictionary's own color transforms (tinycolor2) read an oklch() as invalid and emit
  // black without a word. This runs first: it turns an oklch() color into its sRGB hex (gamut-
  // mapped the way CSS Color 4 tells browsers to, alpha kept), passes every format tinycolor2
  // reads through untouched for those transforms, and throws on anything else. The CSS output
  // keeps colors as written.
  // Not transitive, like the built-in color transforms it feeds: an alias takes its target's
  // finished value (already a UIColor or an Android hex by then), so re-running this on it would
  // be converting the output, not the source.
  instance.registerTransform({
    name: 'color/css-to-hex',
    type: 'value',
    filter: (token, options) => getType(token, options) === 'color',
    transform: (token, _config, options) => {
      const value = getValue(token, options);
      if (/^\s*oklch\(/i.test(value)) return toSrgbHex(value, { allowAlpha: true }).hex;
      if (!tinycolor(value).isValid()) throw new Error(`Unrecognised color "${value}": use hex, rgb(), hsl(), oklch(), or a CSS color name`);
      return value;
    },
  });

  instance.registerTransform({
    name: 'value/js-native',
    type: 'value',
    transitive: true,
    transform: (token, _config, options) => {
      const raw = getValue(token, options);
      switch (getType(token, options)) {
        case 'dimension':
          return roundNum(dimensionToNumber(raw));
        case 'duration':
          return roundNum(durationToMs(raw));
        case 'number':
        case 'fontWeight':
          return roundNum(parseFloat(raw));
        default:
          // color, string (easing/shadow), fontFamily: already good, CSS-ready strings.
          return raw;
      }
    },
  });

  instance.registerTransform({
    name: 'value/ios-dimension-cgfloat',
    type: 'value',
    transitive: true,
    filter: isDeviceDimensionToken,
    transform: (token, _config, options) => `CGFloat(${dimensionToNumber(getValue(token, options)).toFixed(2)})`,
  });

  instance.registerTransform({
    name: 'value/ios-duration-seconds',
    type: 'value',
    transitive: true,
    filter: (token, options) => getType(token, options) === 'duration',
    transform: (token, _config, options) =>
      String(parseFloat((durationToMs(getValue(token, options)) / 1000).toFixed(3))),
  });

  instance.registerTransform({
    name: 'value/android-dimension-dp',
    type: 'value',
    transitive: true,
    filter: (token, options) => isDeviceDimensionToken(token, options) && !isFontSizeToken(token),
    transform: (token, _config, options) => `${dimensionToNumber(getValue(token, options)).toFixed(2)}dp`,
  });

  instance.registerTransform({
    name: 'value/android-fontsize-sp',
    type: 'value',
    transitive: true,
    filter: (token, options) => isDeviceDimensionToken(token, options) && isFontSizeToken(token),
    transform: (token, _config, options) => `${dimensionToNumber(getValue(token, options)).toFixed(2)}sp`,
  });

  instance.registerTransform({
    name: 'value/android-duration-ms',
    type: 'value',
    transitive: true,
    filter: (token, options) => getType(token, options) === 'duration',
    transform: (token, _config, options) => Math.round(durationToMs(getValue(token, options))),
  });
}

// A dimension/color/duration token that's worth emitting to a native (iOS/Android)
// platform at all — see isDeviceDimensionToken + NATIVE_SKIP_EXPLANATION for what's
// deliberately left out and why.
function isNativeToken(token, options) {
  const type = getType(token, options);
  return type === 'color' || type === 'duration' || isDeviceDimensionToken(token, options);
}

