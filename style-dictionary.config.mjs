async function jsTokensTsFormat({ dictionary, file, options }) {
  const exportName = file.options?.exportName ?? 'tokens';
  const typeName = exportName.charAt(0).toUpperCase() + exportName.slice(1);
  const data = minifyDictionary(dictionary.tokens, options.usesDtcg);
  // Deliberately `//` line comments rather than a `/** */` block comment: the source
  // glob "tokens/**/*.json" contains a literal `**/`, which would close a block comment
  // early and corrupt the rest of the file — `//` comments have no such footgun.
  const headerLines = [generatedFileNotice(file.destination), '', ...JS_VALUE_CONVENTION_LINES];
  const header = lineComments(headerLines);
  return (
    `${header}\n` +
    `export const ${exportName} = ${toObjectLiteral(data)} as const;\n\n` +
    `export type ${typeName} = typeof ${exportName};\n\n` +
    `export default ${exportName};\n`
  );
}
// This format builds its output from the token *tree* (via minifyDictionary), not from
// individual `token.name`s, so per-token name uniqueness doesn't matter to it — same as
// style-dictionary's own built-in 'json/nested' format. Flagging it `nested` here (the
// same flag formats.js sets on jsonNested/javascriptEsm/etc.) tells style-dictionary's
// name-collision checker not to warn: with no name-type transform registered for the
// `js` platform (deliberately — nothing here reads token.name), every token's default
// name collapses to just its last path segment, which collides constantly ("sm" from
// breakpoint.sm AND elevation.sm AND font.size.sm, etc.) but is entirely harmless here.
jsTokensTsFormat.nested = true;

StyleDictionary.registerFormat({
  name: 'js/tokens-ts',
  format: jsTokensTsFormat,
});

// React Native shapes for the values the CSS convention above can't carry over
// (scripts/native-tokens.mjs says what each one is and how it's approximated). Derived from the
// authored values, not the JS-transformed ones, so a unit is known rather than assumed; once per
// dictionary, for both the .ts and the .json file.
const nativeByDictionary = new WeakMap();
function nativeTokens(dictionary) {
  if (!nativeByDictionary.has(dictionary)) {
    const tokens = dictionary.allTokens.map((token) => ({
      path: token.path,
      value: token.$value ?? token.value,
      original: token.original?.$value ?? token.original?.value,
    }));
    nativeByDictionary.set(dictionary, deriveNativeTokens(tokens));
  }
  return nativeByDictionary.get(dictionary);
}

