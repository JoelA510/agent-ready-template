#!/usr/bin/env node
// Generates .claude/skills/ from .agents/skills/, the one source for this repo's workflow skills.
//
// .agents/skills/<name>/SKILL.md is the Agent Skills layout that Codex, Antigravity, Gemini CLI,
// Cursor, and GitHub Copilot read. Claude Code reads only .claude/skills/, so each skill is
// copied there with every field it has, plus the two Claude Code settings the portable source
// keeps under `metadata` (where the specification puts tool-specific settings):
//   - `metadata.argument-hint` becomes Claude Code's `argument-hint` (shown in the / menu);
//   - `metadata.invocation: explicit` becomes `disable-model-invocation: true`, so a heavyweight
//     workflow runs only when someone asks for it by name.
// A copy rather than a symlink: a Windows checkout without core.symlinks turns a symlink into a
// one-line text file. check-generated.mjs fails when the copies drift; edit .agents/skills/ and
// run `npm run skills:build`.
//
// Run: node scripts/build-skills.mjs   (npm run skills:build)
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stringify } from 'yaml'
import { SPEC_FIELDS, parseSkill } from './skills.mjs'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const SOURCE = join(ROOT, '.agents', 'skills')
const OUT = join(ROOT, '.claude', 'skills')
// Consumed here, not carried into the copy's metadata.
const CLAUDE_METADATA = ['argument-hint', 'invocation']

if (!existsSync(SOURCE)) {
  console.error('✗ .agents/skills/ does not exist; there is nothing to build .claude/skills/ from.')
  process.exit(2)
}

// Validate every skill before touching the output, so a bad edit leaves the last good copies.
const skills = []
const problems = []
for (const name of readdirSync(SOURCE).sort()) {
  const dir = join(SOURCE, name)
  if (!statSync(dir).isDirectory()) continue
  const file = join(dir, 'SKILL.md')
  if (!existsSync(file)) {
    problems.push(`.agents/skills/${name}/ has no SKILL.md (a leftover directory? delete it)`)
    continue
  }
  const skill = parseSkill(readFileSync(file, 'utf8'), name)
  const invocation = skill.metadata.invocation
  if (invocation !== undefined && invocation !== 'explicit') {
    skill.problems.push(`metadata "invocation" is "${invocation}"; the only value is "explicit"`)
  }
  if (skill.problems.length) problems.push(`.agents/skills/${name}/SKILL.md:\n${skill.problems.map((p) => `  - ${p}`).join('\n')}`)
  else skills.push({ name, skill, files: readdirSync(dir, { recursive: true }).filter((f) => statSync(join(dir, f)).isFile()) })
}
if (problems.length) {
  console.error(`✗ ${problems.join('\n✗ ')}`)
  process.exit(1)
}

function claudeFrontmatter({ fields, metadata }) {
  const out = { name: fields.name, description: fields.description }
  if (metadata['argument-hint']) out['argument-hint'] = metadata['argument-hint']
  if (metadata.invocation === 'explicit') out['disable-model-invocation'] = true
  for (const key of SPEC_FIELDS) {
    if (key === 'name' || key === 'description' || key === 'metadata') continue
    if (Object.hasOwn(fields, key)) out[key] = fields[key]
  }
  const rest = Object.fromEntries(Object.entries(metadata).filter(([k]) => !CLAUDE_METADATA.includes(k)))
  if (Object.keys(rest).length) out.metadata = rest
  return stringify(out, { lineWidth: 0 }).trimEnd()
}

rmSync(OUT, { recursive: true, force: true })
for (const { name, skill, files } of skills) {
  const notice =
    `<!-- Claude Code's copy of .agents/skills/${name}/SKILL.md, generated by the template's skills:build script; ` +
    'its frontmatter differs by design. Edit the .agents/ file and carry the same change into this one. -->'
  for (const rel of files) {
    const dest = join(OUT, name, rel)
    mkdirSync(dirname(dest), { recursive: true })
    const content =
      rel === 'SKILL.md' ? `---\n${claudeFrontmatter(skill)}\n---\n\n${notice}\n${skill.body}` : readFileSync(join(SOURCE, name, rel))
    writeFileSync(dest, content)
  }
}
console.log(`Skills: ${skills.length} copied to .claude/skills/ (${skills.map((s) => s.name).join(', ')})`)
